import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { resolve, join } from 'node:path';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const pages = join(root, 'dist/pages'), server = join(root, 'dist/server');
await mkdir(pages, { recursive: true }); await mkdir(server, { recursive: true }); await mkdir(join(root, 'dist/.openai'), { recursive: true });
await cp(join(root, 'web'), pages, { recursive: true });
execFileSync('go', ['build', '-trimpath', '-ldflags=-s -w', '-o', join(pages, 'generator.wasm'), './cmd/browser'], { cwd: join(root, 'cli'), env: { ...process.env, CGO_ENABLED: '0', GOOS: 'js', GOARCH: 'wasm' }, stdio: 'inherit' });
const goroot = execFileSync('go', ['env', 'GOROOT'], { encoding: 'utf8' }).trim();
await cp(join(goroot, 'lib/wasm/wasm_exec.js'), join(pages, 'wasm_exec.js'));
await writeFile(join(pages, '.nojekyll'), '');
const modules = ['security.mjs', 'plan.mjs', 'git.mjs', 'github.mjs', 'publish.mjs'];
let bundle = "// Generated by scripts/build.mjs. DO NOT EDIT.\nimport { Buffer } from 'node:buffer';\nimport { createHash } from 'node:crypto';\nimport { deflateSync } from 'node:zlib';\n";
for (const path of [...modules.map(m => join(root, 'worker/lib', m)), join(root, 'worker/index.js')]) {
  const code = await readFile(path, 'utf8');
  bundle += '\n' + code.replace(/^import .*;\s*$/gm, '').replace(/^export (?!default)/gm, '') + '\n';
}
await writeFile(join(server, 'index.js'), bundle);
await writeFile(join(server, 'wrangler.json'), JSON.stringify({ name: 'activity-forge-api', main: 'index.js', compatibility_date: '2026-11-10', compatibility_flags: ['nodejs_compat'], observability: { enabled: false } }, null, 2));
await cp(join(root, '.openai/hosting.json'), join(root, 'dist/.openai/hosting.json'));
console.log('Built GitHub Pages frontend (dist/pages) and stateless Worker (dist/server).');
