import { readFile } from 'node:fs/promises';
import '../dist/pages/wasm_exec.js';
import assert from 'node:assert/strict';
import { validatePayload, authorFor } from '../worker/lib/plan.mjs';
import { buildPack } from '../worker/lib/git.mjs';
const go = new Go();
const result = await WebAssembly.instantiate(await readFile(new URL('../dist/pages/generator.wasm', import.meta.url)), go.importObject);
go.run(result.instance);
const call = request => JSON.parse(globalThis.activityForge(JSON.stringify(request)));
const c = call({ action: 'defaults', profile: 'bursts' }).config;
c.start = '2025-01-01'; c.end = '2025-12-31'; c.as_of = '2026-01-01T00:00:00Z';
const a = call({ action: 'generate', config: c, existing: { known: false } });
assert.ok(!a.error, a.error); assert.ok(a.plan.statistics.planned > 0); assert.equal(a.plan.days.length, 365);
const b = call({ action: 'generate', config: c, existing: { known: false } });
assert.equal(a.plan.id, b.plan.id); assert.equal(a.payload, b.payload);
const digest = Buffer.from(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(a.payload))).toString('hex');
assert.equal(digest, a.plan.id);
console.log(`WASM: ${a.plan.days.length} days, ${a.plan.statistics.planned} exact timestamps, deterministic SHA-256 verified.`);
const user = { id: 12345, login: 'example-user' };
const manual = { ...c, start: '2025-06-01', end: '2025-06-07', max: 500, author: authorFor(user), manual: { targets: { '2025-06-01': 7, '2025-06-03': 10 } } };
const existing = { known: true, start: manual.start, end: manual.end, login: user.login, days: Object.fromEntries(Array.from({ length: 7 }, (_, i) => [`2025-06-0${i + 1}`, { contributionCount: i === 0 ? 4 : i === 1 ? 900 : 0, weekday: i }])) };
const drawing = call({ action: 'generate', config: manual, existing });
assert.ok(!drawing.error, drawing.error);
assert.deepEqual(drawing.plan.days.map(d => d.new), [3, 0, 10, 0, 0, 0, 0]);
assert.equal(drawing.plan.days[1].projected, 900);
const validated = await validatePayload(drawing.payload, drawing.plan.id, user);
const pack = buildPack(validated, drawing.plan.id, user);
assert.equal(pack.count, 13);
manual.manual.targets = {};
const blank = call({ action: 'generate', config: manual, existing });
assert.ok(!blank.error, blank.error); assert.equal(blank.plan.statistics.planned, 0);
assert.deepEqual(blank.plan.config.manual, { targets: {} });
console.log('WASM drawing: exact painted counts, empty canvas, baseline preservation, frozen SHA-256 and server/Git pack compatibility verified.');
process.exit(0);
